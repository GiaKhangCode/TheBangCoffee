CREATE OR REPLACE PROCEDURE SP_LAP_PHIEU_NHAP_FULL (
    p_MaTaiKhoan   IN NUMBER,
    p_DanhSach     IN T_LIST_CHI_TIET_PN_FULL,
    p_NgayNhap     IN DATE,
    p_GhiChu       IN NVARCHAR2,
    p_MaPhieuNhap_Out OUT NUMBER
)
AS
    v_TongGiaTri NUMBER := 0;
    v_MaNL_ThucTe NUMBER;
    v_Check_Ingredient NUMBER := 0;
    v_HanSuDung_Date DATE;
    v_SoLuongQuyDoi NUMBER(15,2);
BEGIN
    -- 1. Tính tổng giá trị phiếu nhập
    IF p_DanhSach IS NOT NULL AND p_DanhSach.COUNT > 0 THEN
        FOR i IN 1 .. p_DanhSach.COUNT LOOP
            v_TongGiaTri := v_TongGiaTri + p_DanhSach(i).ThanhTien;
        END LOOP;
    ELSE
        RAISE_APPLICATION_ERROR(-20001, 'Phiếu nhập phải có ít nhất 1 chi tiết nguyên liệu!');
    END IF;

    -- 2. Tạo Phiếu Nhập Kho trước để lấy Mã Phiếu
    INSERT INTO PHIEU_NHAP_KHO (MaTaiKhoan, NgayNhap, TongGiaTri, GhiChu)
    VALUES (p_MaTaiKhoan, p_NgayNhap, v_TongGiaTri, p_GhiChu)
    RETURNING MaPhieuNhap INTO p_MaPhieuNhap_Out;

    -- 3. Xử lý từng dòng chi tiết
    FOR i IN 1 .. p_DanhSach.COUNT LOOP
        IF p_DanhSach(i).HanSuDung IS NOT NULL AND TRIM(p_DanhSach(i).HanSuDung) IS NOT NULL THEN
            v_HanSuDung_Date := TO_DATE(p_DanhSach(i).HanSuDung, 'YYYY-MM-DD');
        ELSE
            v_HanSuDung_Date := NULL;
        END IF;

        v_SoLuongQuyDoi := p_DanhSach(i).SoLuong * p_DanhSach(i).DinhLuong;

        -- A. Master Data - KIỂM TRA TỒN TẠI
        SELECT COUNT(*) INTO v_Check_Ingredient FROM NGUYEN_LIEU
        WHERE UPPER(TenNguyenLieu) = UPPER(p_DanhSach(i).TenNguyenLieu);

        IF v_Check_Ingredient = 0 THEN
            -- [ĐÃ SỬA] KHÔNG TỰ ĐỘNG TẠO MỚI NỮA, MÀ BÁO LỖI LUÔN
            RAISE_APPLICATION_ERROR(-20002, 'Nguyên liệu [' || p_DanhSach(i).TenNguyenLieu || '] chưa có trong Danh mục gốc. Vui lòng thêm nguyên liệu trước khi nhập kho!');
        ELSE
            SELECT MaNguyenLieu INTO v_MaNL_ThucTe FROM NGUYEN_LIEU
            WHERE UPPER(TenNguyenLieu) = UPPER(p_DanhSach(i).TenNguyenLieu) AND ROWNUM = 1;
        END IF;

        -- B. Chi tiết Phiếu nhập
        INSERT INTO CHI_TIET_PHIEU_NHAP (
            MaPhieuNhap, MaNguyenLieu, SoLuong, GiaTruocThue, TienThue, DinhLuong, ThanhTien
        ) VALUES (
            p_MaPhieuNhap_Out, v_MaNL_ThucTe, p_DanhSach(i).SoLuong, p_DanhSach(i).GiaTruocThue,
            p_DanhSach(i).TienThue, p_DanhSach(i).DinhLuong, p_DanhSach(i).ThanhTien
        );

        -- C. Lô Nguyên Liệu
        INSERT INTO LO_NGUYEN_LIEU (
            MaNguyenLieu, MaPhieuNhap, NhaCungCap, SoLuongBanDau, SoLuongConLai, DonGiaQuyDoi, HanSuDung
        ) VALUES (
            v_MaNL_ThucTe, p_MaPhieuNhap_Out, p_DanhSach(i).NhaCungCap, v_SoLuongQuyDoi, v_SoLuongQuyDoi,
            ROUND(p_DanhSach(i).ThanhTien / NULLIF(v_SoLuongQuyDoi, 0), 2), v_HanSuDung_Date
        );
    END LOOP;

    COMMIT;
END;
