-- 2. SP Xóa Hạng (Luồng S-2: Chuyển khách về hạng mặc định)
CREATE OR REPLACE PROCEDURE SP_XOA_HANG_THANH_VIEN (
    p_MaHang IN NUMBER,
    p_KetQua OUT NVARCHAR2
) IS
    v_LaMacDinh NUMBER;
    v_MaMacDinh NUMBER;
BEGIN
    -- Kiểm tra xem có phải hạng mặc định không
    SELECT LaMacDinh INTO v_LaMacDinh FROM HANG_THANH_VIEN WHERE MaHang = p_MaHang;
    IF v_LaMacDinh = 1 THEN
        p_KetQua := N'Lỗi: Không thể xóa hạng Thành viên mặc định!';
        RETURN;
    END IF;

    -- Lấy Mã hạng của hạng Mặc định
    SELECT MaHang INTO v_MaMacDinh FROM HANG_THANH_VIEN WHERE LaMacDinh = 1 AND ROWNUM = 1;

    -- Chuyển toàn bộ khách hàng ở hạng bị xóa về hạng mặc định
    UPDATE KHACH_HANG SET MaHang = v_MaMacDinh WHERE MaHang = p_MaHang;

    -- Xóa hạng
    DELETE FROM HANG_THANH_VIEN WHERE MaHang = p_MaHang;

    COMMIT;
    p_KetQua := N'Thành công';
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

-- 3. SP Đồng bộ thứ hạng (Luồng S-3: Tính toán lại hạng cho toàn bộ KH)
CREATE OR REPLACE PROCEDURE SP_DONG_BO_HANG_THANH_VIEN (
    p_KetQua OUT NVARCHAR2
) IS
BEGIN
    -- Sử dụng MERGE INTO và KEEP DENSE_RANK FIRST của Oracle để tìm Hạng cao nhất
    -- mà khách hàng đủ điều kiện, sau đó Update hàng loạt.
    MERGE INTO KHACH_HANG K
    USING (
        SELECT K_IN.MaKhachHang,
               (SELECT MAX(MaHang) KEEP (DENSE_RANK FIRST ORDER BY DiemYeuCau DESC)
                FROM HANG_THANH_VIEN
                WHERE DiemYeuCau <= K_IN.DiemTichLuy) AS NewMaHang
        FROM KHACH_HANG K_IN
    ) T
    ON (K.MaKhachHang = T.MaKhachHang)
    WHEN MATCHED THEN
        UPDATE SET K.MaHang = T.NewMaHang;

    COMMIT;
    p_KetQua := N'Thành công';
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK; -- Fallback khi mất điện, đứt cáp giữa chừng
        p_KetQua := N'Quá trình đồng bộ bị gián đoạn do sự cố. Dữ liệu đã được khôi phục nguyên trạng.';
END;
/

