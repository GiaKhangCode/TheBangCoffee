-- SỬA NGUYÊN LIỆU
CREATE OR REPLACE PROCEDURE SP_SUA_NGUYEN_LIEU (
    p_MaNguyenLieu IN NUMBER,
    p_TenMoi       IN NVARCHAR2,
    p_DvtMoi       IN NVARCHAR2,
    p_TonMoi       IN NUMBER,
    p_NguongMoi    IN NUMBER,
    p_MaTaiKhoan   IN NUMBER,
    p_LyDo         IN NVARCHAR2,
    p_KetQua       OUT NVARCHAR2
)
IS
    v_TenCu    NGUYEN_LIEU.TenNguyenLieu%TYPE;
    v_DvtCu    NGUYEN_LIEU.DonViTinh%TYPE;
    v_TonCu    NGUYEN_LIEU.SoLuongTon%TYPE;
    v_NguongCu NGUYEN_LIEU.NguongCanhBao%TYPE;
BEGIN
    -- 1. Lấy dữ liệu cũ hiện tại trong kho
    SELECT TenNguyenLieu, DonViTinh, SoLuongTon, NguongCanhBao
    INTO v_TenCu, v_DvtCu, v_TonCu, v_NguongCu
    FROM NGUYEN_LIEU
    WHERE MaNguyenLieu = p_MaNguyenLieu;

    -- 2. Kiểm tra và Ghi log cho từng trường bị thay đổi
    IF v_TenCu != p_TenMoi THEN
        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong, DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, N'Sửa dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu, v_TenCu, p_TenMoi, p_LyDo, SYSDATE);
    END IF;

    IF v_DvtCu != p_DvtMoi THEN
        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong, DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, N'Sửa dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu, v_DvtCu, p_DvtMoi, p_LyDo, SYSDATE);
    END IF;

    IF v_TonCu != p_TonMoi THEN
        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong, DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, N'Sửa dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu, TO_CHAR(v_TonCu), TO_CHAR(p_TonMoi), p_LyDo, SYSDATE);
    END IF;

    IF v_NguongCu != p_NguongMoi THEN
        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong, DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, N'Sửa dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu, TO_CHAR(v_NguongCu), TO_CHAR(p_NguongMoi), p_LyDo, SYSDATE);
    END IF;

    -- 3. Cập nhật dữ liệu mới vào bảng Nguyên Liệu
    UPDATE NGUYEN_LIEU
    SET TenNguyenLieu = p_TenMoi,
        DonViTinh = p_DvtMoi,
        SoLuongTon = p_TonMoi,
        NguongCanhBao = p_NguongMoi
    WHERE MaNguyenLieu = p_MaNguyenLieu;

    COMMIT;
    p_KetQua := N'Thành công';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

