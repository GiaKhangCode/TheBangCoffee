-- XÓA NGUYÊN LIỆU
CREATE OR REPLACE PROCEDURE SP_XOA_NGUYEN_LIEU (
    p_MaNguyenLieu IN NUMBER,
    p_MaTaiKhoan   IN NUMBER,
    p_LyDo         IN NVARCHAR2,
    p_KetQua       OUT NVARCHAR2
)
IS
    v_DuLieuCu VARCHAR2(4000);
    v_Count_CT NUMBER := 0;
    v_Count_Topping NUMBER := 0;
    v_Count_Lo NUMBER := 0;
    v_DanhSachCT NVARCHAR2(2000);
    v_DanhSachTopping NVARCHAR2(2000);
    v_ThongBao NVARCHAR2(4000) := '';
BEGIN
    -- 1. Lấy dữ liệu cũ để lưu Log
    SELECT 'Tên: ' || TenNguyenLieu || '; ĐVT: ' || DonViTinh || '; Tồn kho: ' || SoLuongTon || '; Ngưỡng: ' || NguongCanhBao
    INTO v_DuLieuCu
    FROM NGUYEN_LIEU
    WHERE MaNguyenLieu = p_MaNguyenLieu;

    -- 2. Kiểm tra ràng buộc CÔNG THỨC
    SELECT COUNT(*) INTO v_Count_CT FROM CONG_THUC WHERE MaNguyenLieu = p_MaNguyenLieu;
    IF v_Count_CT > 0 THEN
        SELECT LISTAGG(TenSanPham, ', ') WITHIN GROUP (ORDER BY TenSanPham)
        INTO v_DanhSachCT
        FROM (
            SELECT DISTINCT sp.TenSanPham 
            FROM CONG_THUC ct 
            JOIN BIEN_THE bt ON ct.MaBienThe = bt.MaBienThe 
            JOIN SAN_PHAM sp ON bt.MaSanPham = sp.MaSanPham 
            WHERE ct.MaNguyenLieu = p_MaNguyenLieu
        );
        
        v_ThongBao := 'Nguyên liệu vẫn còn cấu hình trong công thức: ' || v_DanhSachCT;
    END IF;

    -- 3. Kiểm tra ràng buộc TOPPING
    SELECT COUNT(*) INTO v_Count_Topping FROM TOPPING WHERE MaNguyenLieuTru = p_MaNguyenLieu;
    IF v_Count_Topping > 0 THEN
        SELECT LISTAGG(TenTopping, ', ') WITHIN GROUP (ORDER BY TenTopping)
        INTO v_DanhSachTopping
        FROM (
            SELECT DISTINCT TenTopping
            FROM TOPPING 
            WHERE MaNguyenLieuTru = p_MaNguyenLieu
        );
        
        IF v_ThongBao IS NOT NULL AND LENGTH(v_ThongBao) > 0 THEN
            v_ThongBao := v_ThongBao || CHR(10) || 'Nguyên liệu vẫn còn gán với topping: ' || v_DanhSachTopping;
        ELSE
            v_ThongBao := 'Nguyên liệu vẫn còn gán với topping: ' || v_DanhSachTopping;
        END IF;
    END IF;

    IF v_ThongBao IS NOT NULL AND LENGTH(v_ThongBao) > 0 THEN
        p_KetQua := v_ThongBao;
        RETURN;
    END IF;

    -- 4. Kiểm tra xem đã bán/tiêu hao chưa (Lô hàng có SoLuongBanDau > SoLuongConLai)
    SELECT COUNT(*) INTO v_Count_Lo FROM LO_NGUYEN_LIEU 
    WHERE MaNguyenLieu = p_MaNguyenLieu AND SoLuongBanDau > SoLuongConLai;

    IF v_Count_Lo > 0 THEN
        -- Đã bán (Đã tiêu hao) -> XÓA MỀM
        UPDATE NGUYEN_LIEU SET DaXoa = 1 WHERE MaNguyenLieu = p_MaNguyenLieu;
        
        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong,
                                        DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, 'Xóa mềm dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu,
                v_DuLieuCu, 'DaXoa=1', p_LyDo, SYSDATE);
    ELSE
        -- Chưa bán -> XÓA CỨNG (Xóa sạch từ Lô hàng, Chi tiết phiếu nhập)
        DELETE FROM CHI_TIET_PHIEU_NHAP WHERE MaNguyenLieu = p_MaNguyenLieu;
        DELETE FROM LO_NGUYEN_LIEU WHERE MaNguyenLieu = p_MaNguyenLieu;
        DELETE FROM NGUYEN_LIEU WHERE MaNguyenLieu = p_MaNguyenLieu;

        INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong,
                                        DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
        VALUES (p_MaTaiKhoan, 'Xóa cứng dữ liệu', 'NGUYEN_LIEU', p_MaNguyenLieu,
                v_DuLieuCu, NULL, p_LyDo, SYSDATE);
    END IF;

    COMMIT;
    p_KetQua := 'Thành công';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := 'Lỗi hệ thống: ' || SQLERRM;
END;
/

CREATE OR REPLACE PROCEDURE SP_XOA_PHIEU_NHAP (
    p_MaPhieuNhap IN NUMBER,
    p_MaTaiKhoan  IN NUMBER,
    p_LyDo        IN NVARCHAR2,
    p_KetQua      OUT NVARCHAR2
)
IS
    v_DuLieuCu   CLOB;
    v_NgayNhap   DATE;
    v_TongGiaTri NUMBER;
    v_GhiChu     VARCHAR2(255);
    v_Count      NUMBER;
BEGIN
    -- 0. Kiểm tra phiếu nhập có tồn tại không (Ví dụ có 2 người cùng thao tác)
    SELECT COUNT(*) INTO v_Count
    FROM PHIEU_NHAP_KHO
    WHERE MaPhieuNhap = p_MaPhieuNhap;

    IF v_Count = 0 THEN
        p_KetQua := N'Lỗi: Không tìm thấy phiếu nhập này trong hệ thống.';
        RETURN;
    END IF;

    -- 1. Trích xuất thông tin Phiếu nhập để làm dữ liệu cũ (DuLieuCu)
    SELECT NgayNhap, TongGiaTri, GhiChu
    INTO v_NgayNhap, v_TongGiaTri, v_GhiChu
    FROM PHIEU_NHAP_KHO
    WHERE MaPhieuNhap = p_MaPhieuNhap;

    v_DuLieuCu := 'Ngày nhập: ' || TO_CHAR(v_NgayNhap, 'DD/MM/YYYY') ||
                  '; Tổng tiền: ' || v_TongGiaTri ||
                  '; Ghi chú: ' || v_GhiChu;

    -- 2. Ghi Log hệ thống
    INSERT INTO NHAT_KY_HE_THONG (MaTaiKhoan, HanhDong, TenBang, MaDoiTuong,
                                DuLieuCu, DuLieuMoi, LyDo, ThoiDiemThucHien)
    VALUES (p_MaTaiKhoan, N'Xóa dữ liệu', 'PHIEU_NHAP_KHO', p_MaPhieuNhap,
                v_DuLieuCu, NULL, p_LyDo, CURRENT_TIMESTAMP);

    -- 3. Cập nhật lại số lượng tồn kho (QUAN TRỌNG: Lấy số lượng từ phiếu nhập để trừ đi)
    FOR item IN (SELECT MaNguyenLieu, SoLuong
                 FROM CHI_TIET_PHIEU_NHAP
                 WHERE MaPhieuNhap = p_MaPhieuNhap)
    LOOP
        UPDATE NGUYEN_LIEU
        SET SoLuongTon = SoLuongTon - item.SoLuong
        WHERE MaNguyenLieu = item.MaNguyenLieu;
    END LOOP;

    -- 4. Xóa dữ liệu ở bảng con (Chi tiết phiếu nhập)
    DELETE FROM CHI_TIET_PHIEU_NHAP
    WHERE MaPhieuNhap = p_MaPhieuNhap;

    -- 5. Xóa dữ liệu ở bảng cha (Phiếu nhập kho)
    DELETE FROM PHIEU_NHAP_KHO
    WHERE MaPhieuNhap = p_MaPhieuNhap;

    -- Hoàn tất giao dịch
    COMMIT;
    p_KetQua := N'Thành công';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        -- Nếu việc trừ tồn kho làm cho số lượng bị âm (vi phạm CHECK constraint SoLuongTon >= 0), nó sẽ báo lỗi tại đây và rollback toàn bộ.
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

