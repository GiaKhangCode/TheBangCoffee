CREATE OR REPLACE PROCEDURE SP_INSERT_CT_TUY_CHON(
    p_MaSanPham IN NUMBER,
    p_TenTuyChon IN VARCHAR2,
    p_TenNhomTuyChon IN VARCHAR2
)
AS
    v_MaTuyChon NUMBER;
BEGIN
    -- Tìm mã tùy chọn dựa trên Tên tùy chọn và Tên nhóm
    BEGIN
        SELECT T.MaTuyChon
        INTO v_MaTuyChon
        FROM TUY_CHON T
                 JOIN NHOM_TUY_CHON N ON T.MaNhomTuyChon = N.MaNhomTuyChon
        WHERE T.TenTuyChon = p_TenTuyChon
          AND N.TenNhomTuyChon = p_TenNhomTuyChon;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_MaTuyChon := NULL; -- Nếu không có thì gán NULL
    END;

    -- Chỉ Insert nếu tìm thấy mã hợp lệ
    IF v_MaTuyChon IS NOT NULL THEN
        INSERT INTO CHI_TIET_TUY_CHON_SAN_PHAM (MaSanPham, MaTuyChon)
        VALUES (p_MaSanPham, v_MaTuyChon);
    END IF;

    COMMIT;
END;
