-- 3. Cập nhật Procedure
CREATE OR REPLACE PROCEDURE SP_LAP_PHIEU_NHAP_FULL (
    p_MaTaiKhoan      IN NUMBER,
    p_DanhSachChiTiet IN T_LIST_CHI_TIET_PN_FULL,
    p_NgayNhap        IN PHIEU_NHAP_KHO.NgayNhap%type,
    p_MaPhieuNhap_Out OUT NUMBER
)
AS
    v_TongGiaTri NUMBER := 0;
    v_MaNL_ThucTe NUMBER;
    v_Check_Ingredient NUMBER := 0;
    v_HanSuDung_Date DATE;
BEGIN
    IF p_DanhSachChiTiet IS NOT NULL AND p_DanhSachChiTiet.COUNT > 0 THEN
        FOR i IN 1 .. p_DanhSachChiTiet.COUNT LOOP
            v_TongGiaTri := v_TongGiaTri + p_DanhSachChiTiet(i).ThanhTien;
        END LOOP;
    ELSE
        RAISE_APPLICATION_ERROR(-20001, 'Phiếu nhập phải có ít nhất 1 chi tiết nguyên liệu!');
    END IF;

    INSERT INTO PHIEU_NHAP_KHO (MaTaiKhoan, NgayNhap, TongGiaTri)
    VALUES (p_MaTaiKhoan, p_NgayNhap, v_TongGiaTri)
    RETURNING MaPhieuNhap INTO p_MaPhieuNhap_Out;

    FOR i IN 1 .. p_DanhSachChiTiet.COUNT LOOP


        v_HanSuDung_Date := TO_DATE(p_DanhSachChiTiet(i).HanSuDung, 'YYYY-MM-DD');

        SELECT COUNT(*) INTO v_Check_Ingredient FROM NGUYEN_LIEU
        WHERE UPPER(TenNguyenLieu) = UPPER(p_DanhSachChiTiet(i).TenNguyenLieu)
          AND TRUNC(HanSuDung) = TRUNC(v_HanSuDung_Date);

        IF v_Check_Ingredient = 0 THEN
            INSERT INTO NGUYEN_LIEU (
                MaLoaiNguyenLieu, TenNguyenLieu, DonViTinh, SoLuongTon, NhaCungCap, NguongCanhBao, HanSuDung
            ) VALUES (
                p_DanhSachChiTiet(i).MaLoaiNguyenLieu, p_DanhSachChiTiet(i).TenNguyenLieu,
                p_DanhSachChiTiet(i).DonViTinh, p_DanhSachChiTiet(i).SoLuong,
                p_DanhSachChiTiet(i).NhaCungCap, p_DanhSachChiTiet(i).NguongCanhBao,
                v_HanSuDung_Date -- Lưu ngày chuẩn vào bảng
            ) RETURNING MaNguyenLieu INTO v_MaNL_ThucTe;
        ELSE
            SELECT MaNguyenLieu INTO v_MaNL_ThucTe FROM NGUYEN_LIEU
            WHERE UPPER(TenNguyenLieu) = UPPER(p_DanhSachChiTiet(i).TenNguyenLieu)
              AND TRUNC(HanSuDung) = TRUNC(v_HanSuDung_Date)
              AND ROWNUM = 1;

            UPDATE NGUYEN_LIEU
            SET SoLuongTon = SoLuongTon + p_DanhSachChiTiet(i).SoLuong
            WHERE MaNguyenLieu = v_MaNL_ThucTe;
        END IF;

        INSERT INTO CHI_TIET_PHIEU_NHAP (MaPhieuNhap, MaNguyenLieu, SoLuong, ThanhTien, TongDinhLuong)
        VALUES (
            p_MaPhieuNhap_Out, v_MaNL_ThucTe, p_DanhSachChiTiet(i).SoLuong, p_DanhSachChiTiet(i).ThanhTien,
            p_DanhSachChiTiet(i).TongDinhLuong
        );
    END LOOP;
    COMMIT;
END;
