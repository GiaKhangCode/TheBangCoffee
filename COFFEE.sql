CREATE OR REPLACE PROCEDURE SP_UPDATE_SAN_PHAM(
    p_MaSanPham      IN NUMBER,
    p_TenSanPham     IN NVARCHAR2,
    p_ThueGTGT       IN NUMBER,
    p_TenAnhSanPham  IN NVARCHAR2,
    p_KieuDuLieuAnh  IN VARCHAR2,
    p_DuLieuAnh      IN BLOB,
    p_TrangThai      IN NVARCHAR2,
    p_TenLoaiSanPham IN NVARCHAR2
)
AS
    v_MaLoaiSanPham NUMBER;
BEGIN
    -- Lấy Mã Loại Sản Phẩm từ Tên Loại
    SELECT MaLoaiSanPham INTO v_MaLoaiSanPham
    FROM LOAI_SAN_PHAM WHERE TenLoaiSanPham = p_TenLoaiSanPham;

    -- Giá sản phẩm không còn lưu ở bảng SAN_PHAM nữa (chỉ lưu ở BIEN_THE)
    -- Nếu người dùng có chọn ảnh mới thì cập nhật cả ảnh
    IF p_DuLieuAnh IS NOT NULL THEN
        UPDATE SAN_PHAM
        SET MaLoaiSanPham = v_MaLoaiSanPham,
            TenSanPham = p_TenSanPham,
            Thue_GTGT = p_ThueGTGT,
            TenAnhSanPham = p_TenAnhSanPham,
            KieuDuLieuAnh = p_KieuDuLieuAnh,
            DuLieuAnh = p_DuLieuAnh,
            TrangThai = p_TrangThai
        WHERE MaSanPham = p_MaSanPham;
    ELSE
        -- Nếu không chọn ảnh mới thì giữ nguyên ảnh cũ
        UPDATE SAN_PHAM
        SET MaLoaiSanPham = v_MaLoaiSanPham,
            TenSanPham = p_TenSanPham,
            Thue_GTGT = p_ThueGTGT,
            TrangThai = p_TrangThai
        WHERE MaSanPham = p_MaSanPham;
    END IF;

    COMMIT;
END;

CREATE OR REPLACE TRIGGER TRG_CAPNHAT_DONGIA_BINHQUAN
FOR INSERT OR UPDATE OR DELETE ON LO_NGUYEN_LIEU
COMPOUND TRIGGER

    -- Khai báo mảng để lưu danh sách các mã nguyên liệu bị thay đổi.
    -- Dùng mảng băm (associative array) để tự động loại bỏ các mã trùng lặp (vd: nhập 1 lúc 5 lô của cùng 1 NL).
    TYPE t_nguyen_lieu IS TABLE OF BOOLEAN INDEX BY PLS_INTEGER;
    v_nguyen_lieu_map t_nguyen_lieu;
    v_ma_nl PLS_INTEGER;

    -- 1. Giai đoạn AFTER EACH ROW (Kích hoạt sau mỗi dòng bị tác động)
    -- Mục đích: Ghi nhận lại Mã Nguyên Liệu nào vừa bị thêm/sửa/xóa lô hàng.
    AFTER EACH ROW IS
    BEGIN
        IF INSERTING OR UPDATING THEN
            v_nguyen_lieu_map(:NEW.MaNguyenLieu) := TRUE;
        END IF;

        -- Xử lý thêm trường hợp xóa lô hoặc thay đổi mã NL của lô (dù hiếm)
        IF DELETING OR (UPDATING AND :OLD.MaNguyenLieu != :NEW.MaNguyenLieu) THEN
            v_nguyen_lieu_map(:OLD.MaNguyenLieu) := TRUE;
        END IF;
    END AFTER EACH ROW;

    -- 2. Giai đoạn AFTER STATEMENT (Kích hoạt 1 lần duy nhất sau khi toàn bộ câu lệnh chạy xong)
    -- Mục đích: Tính toán lại tổng số lượng và đơn giá bình quân, sau đó cập nhật bảng NGUYEN_LIEU.
    AFTER STATEMENT IS
        v_tong_gia_tri NUMBER(15, 2);
        v_tong_so_luong NUMBER(15, 2);
        v_don_gia_bq NUMBER(15, 2);
    BEGIN
        -- Lấy mã nguyên liệu đầu tiên trong mảng
        v_ma_nl := v_nguyen_lieu_map.FIRST;

        -- Duyệt qua từng nguyên liệu đã bị ảnh hưởng
        WHILE v_ma_nl IS NOT NULL LOOP

            -- Tính tổng giá trị và tổng số lượng tồn của nguyên liệu đó từ các lô hàng
            SELECT NVL(SUM(SoLuongConLai * DonGiaQuyDoi), 0),
                   NVL(SUM(SoLuongConLai), 0)
            INTO v_tong_gia_tri, v_tong_so_luong
            FROM LO_NGUYEN_LIEU
            WHERE MaNguyenLieu = v_ma_nl
              AND SoLuongConLai > 0; -- Chỉ tính những lô đang còn hàng

            -- Tính đơn giá bình quân
            IF v_tong_so_luong > 0 THEN
                v_don_gia_bq := v_tong_gia_tri / v_tong_so_luong;
            ELSE
                v_don_gia_bq := 0; -- Nếu kho hết sạch hàng thì trả về 0
            END IF;

            -- Cập nhật vào bảng NGUYEN_LIEU
            -- Tiện thể: Trigger tự cập nhật luôn SoLuongTon để kho tổng tự động đồng bộ với chi tiết các lô
            UPDATE NGUYEN_LIEU
            SET DonGiaBinhQuan = v_don_gia_bq,
                SoLuongTon = v_tong_so_luong
            WHERE MaNguyenLieu = v_ma_nl;

            -- Chuyển sang nguyên liệu tiếp theo trong mảng
            v_ma_nl := v_nguyen_lieu_map.NEXT(v_ma_nl);
        END LOOP;

        -- Xóa mảng để giải phóng bộ nhớ
        v_nguyen_lieu_map.DELETE;
    END AFTER STATEMENT;

END TRG_CAPNHAT_DONGIA_BINHQUAN;
