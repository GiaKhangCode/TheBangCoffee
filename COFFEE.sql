CREATE OR REPLACE PROCEDURE SP_DANG_KY_TAI_KHOAN(
    p_HoTen IN NGUOI_DUNG.HoTen%Type,
    p_Email IN NGUOI_DUNG.Email%type,
    p_SoDienThoai IN NGUOI_DUNG.SoDienThoai%type,
    p_TenDangNhap IN TAI_KHOAN.TenDangNhap%type,
    p_MatKhauMaHoa IN TAI_KHOAN.MatKhauDaMaHoa%type,

    --- Output
    p_KetQua OUT NVARCHAR2
)
    IS
    v_MaNguoiDung NGUOI_DUNG.MaNguoiDung%TYPE;
    v_MaTaiKhoan  NUMBER;
    v_Count       NUMBER;
BEGIN
    -- 1. Kiểm tra các dữ liệu UNIQUE bằng COUNT (Dành cho các luồng xử lý thông thường)
    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE Email = p_Email;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Email này đã được đăng ký.';
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE SoDienThoai = p_SoDienThoai;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Số điện thoại này đã được đăng ký.';
        RETURN;
    END IF;

    SELECT COUNT(*) INTO v_Count FROM TAI_KHOAN WHERE TenDangNhap = p_TenDangNhap;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Tên đăng nhập đã tồn tại. Vui lòng chọn tên khác.';
        RETURN;
    END IF;

    -- 2. Insert dữ liệu
    INSERT INTO NGUOI_DUNG (HoTen, Email, SoDienThoai)
    VALUES (p_HoTen, p_Email, p_SoDienThoai)
    RETURNING MaNguoiDung INTO v_MaNguoiDung;

    INSERT INTO TAI_KHOAN (MaNguoiDung, TenDangNhap, MatKhauDaMaHoa)
    VALUES (v_MaNguoiDung, p_TenDangNhap, p_MatKhauMaHoa)
    RETURNING MaTaiKhoan INTO v_MaTaiKhoan;

    -- 4. Hoàn tất
    COMMIT;
    p_KetQua := N'Thành công';

EXCEPTION
    -- Bắt lỗi Race Condition (Nếu 2 request lọt qua vòng COUNT cùng lúc)
    WHEN DUP_VAL_ON_INDEX THEN
        ROLLBACK;
        p_KetQua :=
                N'Lỗi: Thông tin (Email, SĐT hoặc Tên đăng nhập) đã tồn tại trong hệ thống do có giao dịch đồng thời.';

    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
/

CREATE OR REPLACE PROCEDURE SP_SUA_TAI_KHOAN_NV(
    p_MaTaiKhoan IN NUMBER,
    p_HoTen IN NGUOI_DUNG.HoTen%Type,
    p_Email IN NGUOI_DUNG.Email%type,
    p_SoDienThoai IN NGUOI_DUNG.SoDienThoai%type,

    --- Output
    p_KetQua OUT NVARCHAR2
)
IS
    v_MaNguoiDung NGUOI_DUNG.MaNguoiDung%TYPE;
    v_Count NUMBER;
BEGIN
    -- Lấy Mã Người Dùng
    SELECT MaNguoiDung INTO v_MaNguoiDung FROM TAI_KHOAN WHERE MaTaiKhoan = p_MaTaiKhoan;

    -- Kiểm tra Email trùng (loại trừ user hiện tại)
    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE Email = p_Email AND MaNguoiDung <> v_MaNguoiDung;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Email này đã được đăng ký cho người khác.';
        RETURN;
    END IF;

    -- Kiểm tra SĐT trùng
    SELECT COUNT(*) INTO v_Count FROM NGUOI_DUNG WHERE SoDienThoai = p_SoDienThoai AND MaNguoiDung <> v_MaNguoiDung;
    IF v_Count > 0 THEN
        p_KetQua := N'Lỗi: Số điện thoại này đã được đăng ký cho người khác.';
        RETURN;
    END IF;

    -- Cập nhật thông tin
    UPDATE NGUOI_DUNG
    SET HoTen = p_HoTen, Email = p_Email, SoDienThoai = p_SoDienThoai
    WHERE MaNguoiDung = v_MaNguoiDung;

    COMMIT;
    p_KetQua := N'Thành công';

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        p_KetQua := N'Lỗi hệ thống: ' || SQLERRM;
END;
